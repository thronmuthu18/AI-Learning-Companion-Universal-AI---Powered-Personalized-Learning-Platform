/**
 * Reports content availability transparently across all domains without claiming
 * every domain already has complete bundled lessons.
 */
export function getDomainContentCoverage(
  domains: DomainDefinition[],
  resources: LearningResource[],
  skillDomainMap: Record<string, string | undefined>,
): DomainContentCoverage[] {
  return domains.map((d) => {
    const matching = resources.filter(
      (r) => r.domainId === d.id || skillDomainMap[r.skillId] === d.id,
    );
    const bundledCount = matching.filter((r) => r.origin === 'bundled').length;
    const importedOrUserCount = matching.filter((r) => r.origin === 'user_imported').length;
    const status: ContentAvailabilityStatus =
      bundledCount > 0 ? d.contentStatus : importedOrUserCount > 0 ? 'user_created' : d.contentStatus;
    return {
      domainId: d.id,
      domainName: d.name,
      status,
      bundledCount,
      importedOrUserCount,
    };
  });
}
